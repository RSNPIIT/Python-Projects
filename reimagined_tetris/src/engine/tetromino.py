# Standard Guideline SRS Wall Kick Tables
# Note: In grid coordinates, +dx is Right, +dy is Down.
# Guideline kicks are defined with +Y = Up, so dy = -guide_y.

JLSTZ_KICKS = {
    (0, 1): [(0, 0), (-1, 0), (-1, -1), (0, 2), (-1, 2)],
    (1, 0): [(0, 0), (1, 0), (1, 1), (0, -2), (1, -2)],
    (1, 2): [(0, 0), (1, 0), (1, 1), (0, -2), (1, -2)],
    (2, 1): [(0, 0), (-1, 0), (-1, -1), (0, 2), (-1, 2)],
    (2, 3): [(0, 0), (1, 0), (1, -1), (0, 2), (1, 2)],
    (3, 2): [(0, 0), (-1, 0), (-1, 1), (0, -2), (-1, -2)],
    (3, 0): [(0, 0), (-1, 0), (-1, 1), (0, -2), (-1, -2)],
    (0, 3): [(0, 0), (1, 0), (1, -1), (0, 2), (1, 2)],
}

I_KICKS = {
    (0, 1): [(0, 0), (-2, 0), (1, 0), (-2, 1), (1, -2)],
    (1, 0): [(0, 0), (2, 0), (-1, 0), (2, -1), (-1, 2)],
    (1, 2): [(0, 0), (-1, 0), (2, 0), (-1, -2), (2, 1)],
    (2, 1): [(0, 0), (1, 0), (-2, 0), (1, 2), (-2, -1)],
    (2, 3): [(0, 0), (2, 0), (-1, 0), (2, -1), (-1, 2)],
    (3, 2): [(0, 0), (-2, 0), (1, 0), (-2, 1), (1, -2)],
    (3, 0): [(0, 0), (1, 0), (-2, 0), (1, 2), (-2, -1)],
    (0, 3): [(0, 0), (-1, 0), (2, 0), (-1, -2), (2, 1)],
}


class Tetromino:
    def __init__(self, kind, x=0, y=0, rotation=0):
        self.kind = kind
        self.x = x
        self.y = y
        self.rotation = rotation % 4
        self.color = TETROMINO_COLORS[kind]
        self.last_move_was_rotation = False
        self.last_kick_index = 0

    @property
    def matrix(self):
        return SHAPES[self.kind][self.rotation]

    @property
    def size(self):
        return len(self.matrix)

    def get_blocks(self, offset_x=None, offset_y=None, rotation=None):
        ox = self.x if offset_x is None else offset_x
        oy = self.y if offset_y is None else offset_y
        rot = self.rotation if rotation is None else (rotation % 4)
        shape_mat = SHAPES[self.kind][rot]
        blocks = []
        for r_idx, row in enumerate(shape_mat):
            for c_idx, val in enumerate(row):
                if val:
                    blocks.append((ox + c_idx, oy + r_idx))
        return blocks

    def get_wall_kicks(self, from_rot, to_rot):
        pair = (from_rot % 4, to_rot % 4)
        if self.kind == 'O':
            return [(0, 0)]
        elif self.kind == 'I':
            return I_KICKS.get(pair, [(0, 0)])
        else:
            return JLSTZ_KICKS.get(pair, [(0, 0)])

    def clone(self):
        cloned = Tetromino(self.kind, self.x, self.y, self.rotation)
        cloned.last_move_was_rotation = self.last_move_was_rotation
        cloned.last_kick_index = self.last_kick_index
        return cloned
